import AppKit
import HaloCore

/// The general pasteboard around synthetic copy/paste.
///
/// Text Halo puts there only to paste it is marked with the nspasteboard.org types, so clipboard
/// managers don't record it, and the previous contents are restored afterwards unless something
/// else has written to the pasteboard in the meantime (changeCount guard).
enum Clipboard {
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    static var changeCount: Int { NSPasteboard.general.changeCount }

    /// Plain text currently on the pasteboard.
    static var string: String? { NSPasteboard.general.string(forType: .string) }

    /// Writes `text` for Halo's own paste (hidden from clipboard history); returns the changeCount
    /// that identifies it.
    @discardableResult
    static func writeTransient(_ text: String) -> Int {
        write(text, markers: [transientType, autoGeneratedType])
    }

    /// Writes `text` for the user to paste themselves (kept in clipboard history).
    static func write(_ text: String) {
        _ = write(text, markers: [])
    }

    private static func write(_ text: String, markers: [NSPasteboard.PasteboardType]) -> Int {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for marker in markers { item.setData(Data(), forType: marker) }
        item.setString(Bundle.main.bundleIdentifier ?? "Halo", forType: sourceType)
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// Waits until the pasteboard changes from `count` (an app answering ⌘C/⌘X); false on timeout.
    static func waitForChange(from count: Int, timeout: Duration) async -> Bool {
        let deadline = ContinuousClock.now + timeout
        while NSPasteboard.general.changeCount == count {
            guard ContinuousClock.now < deadline else { return false }
            try? await Task.sleep(for: .milliseconds(15))
        }
        return true
    }

    /// A copy of everything on the pasteboard, to put back later.
    struct Snapshot {
        private let items: [NSPasteboardItem]

        /// nil when the user set Halo's pasteboard access to "Deny" (nothing could be restored).
        static func capture() -> Snapshot? {
            let pasteboard = NSPasteboard.general
            guard pasteboard.accessBehavior != .alwaysDeny else { return nil }
            let items = (pasteboard.pasteboardItems ?? []).map { original in
                let copy = NSPasteboardItem()
                for type in original.types {
                    if let data = original.data(forType: type) { copy.setData(data, forType: type) }
                }
                return copy
            }
            return Snapshot(items: items)
        }

        /// Puts the saved contents back if the pasteboard still holds what Halo left there
        /// (`expected`); a newer copy by the user or an app is never overwritten.
        func restore(ifChangeCountIs expected: Int) {
            let pasteboard = NSPasteboard.general
            guard pasteboard.changeCount == expected else { return }
            pasteboard.clearContents()
            guard !items.isEmpty else { return }
            // Clipboard managers already recorded these when they were first copied.
            items.first?.setData(Data(), forType: transientType)
            pasteboard.writeObjects(items)
        }
    }
}

/// Runs clipboard work one piece at a time, in order. Interleaved, two save → write → restore
/// sequences lose the user's clipboard (the second saves the first one's transient text and puts
/// that back), and a write in between makes a paste send the wrong text. Not reentrant: take it
/// only around the clipboard work itself, never around a caller that takes it too.
enum ClipboardLock {
    private static var isHeld = false
    private static var waiting: [CheckedContinuation<Void, Never>] = []

    static func run<T>(_ work: @MainActor () async -> T) async -> T {
        if isHeld {
            await withCheckedContinuation { waiting.append($0) }   // handed over still held
        } else {
            isHeld = true
        }
        defer { handOver() }
        return await work()
    }

    private static func handOver() {
        if waiting.isEmpty {
            isHeld = false
        } else {
            waiting.removeFirst().resume()
        }
    }
}

/// Reads the text selected in the frontmost app by sending ⌘C, then restores the clipboard.
enum SelectionReader {
    /// The selection, or nil when nothing was copied (no selection, or the app ignored ⌘C).
    /// Needs Accessibility (checked by the caller).
    static func read() async -> String? {
        await KeySender.waitForTriggerRelease()
        return await ClipboardLock.run {
            let snapshot = Clipboard.Snapshot.capture()
            let before = Clipboard.changeCount
            guard await KeySender.press(character: "c", modifiers: .maskCommand, fallback: CGKeyCode(KeyCode.c)),
                  await Clipboard.waitForChange(from: before, timeout: .milliseconds(800)) else { return nil }
            // An app may clear the pasteboard a moment before writing to it.
            var text = Clipboard.string
            for _ in 0..<5 where text == nil {
                try? await Task.sleep(for: .milliseconds(20))
                text = Clipboard.string
            }
            snapshot?.restore(ifChangeCountIs: Clipboard.changeCount)
            return text
        }
    }
}
